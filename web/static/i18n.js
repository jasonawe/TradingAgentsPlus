  function clean(value) {
    if (value == null) return "";
    return String(value).trim();
  }

  function interpolate(value, vars) {
    return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  }

  function t(key, vars = {}) {
    const normalized = clean(key);
    const value = Object.prototype.hasOwnProperty.call(RESOURCES, normalized)
      ? RESOURCES[normalized]
      : normalized;
    return interpolate(value, vars);
  }

  function displayValue(value, placeholder = RESOURCES["common.none"]) {
    return clean(value) || placeholder;
  }

  function label(namespace, key, fallback) {
    const raw = clean(key);
    if (!raw) return displayValue(fallback);
    const resourceKey = `${clean(namespace)}.${raw.toLowerCase()}`;
    return Object.prototype.hasOwnProperty.call(RESOURCES, resourceKey)
      ? RESOURCES[resourceKey]
      : displayValue(fallback == null ? raw : fallback);
  }

  function preferredValue(...values) {
    return displayValue(values.find((value) => clean(value)));
  }

  function assetIdentity(payload = {}) {
    return {
      name: preferredValue(
        payload.asset_name_zh,
        payload.name_zh,
        payload.asset_name,
        payload.name,
        payload.raw_summary,
        payload.quote && payload.quote.raw_summary,
      ),
      exchange: preferredValue(
        payload.exchange_name_zh,
        payload.exchange,
        payload.quote && payload.quote.exchange,
      ),
    };
  }

  return Object.freeze({
    locale: "zh-CN",
    resources: RESOURCES,
    t,
    label,
    displayValue,
    preferredValue,
    assetIdentity,
  });
